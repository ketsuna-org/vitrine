// Build assets/icons/pixelarticons.svg from the Pixelarticons SVGs used by the app.
// Usage: node scripts/build-pixel-sprite.mjs [path/to/pixelarticons]
// Default source: ../bot-creator/packages/ui/assets/icons/pixelarticons (workspace layout).
// Ids are the legacy Material names used by templates; the map gives the Pixelarticons file for each.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const src = resolve(process.argv[2] ?? new URL('../../bot-creator/packages/ui/assets/icons/pixelarticons', import.meta.url).pathname);
const aliases = JSON.parse(await readFile(new URL('../assets/icons/pixelarticons-map.json', import.meta.url), 'utf8'));
const symbols = [];
for (const [id, name] of Object.entries(aliases)) {
  const svg = await readFile(resolve(src, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]+)"[^>]*>/g)].map((m) => `<path fill="currentColor" shape-rendering="crispEdges" d="${m[1]}"/>`);
  if (!paths.length) throw new Error(`No path in ${name}.svg`);
  symbols.push(`<symbol id="${id}" viewBox="0 0 24 24">${paths.join('')}</symbol>`);
}
await writeFile(new URL('../assets/icons/pixelarticons.svg', import.meta.url),
  `<!-- Pixelarticons 2.4.2 (MIT, see LICENSE-Pixelarticons.txt). Generated by scripts/build-pixel-sprite.mjs -->\n` +
  `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`);
console.log(`Generated ${symbols.length} symbols.`);
